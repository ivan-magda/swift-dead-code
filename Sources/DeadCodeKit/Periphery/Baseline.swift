import Foundation

/// The recorded backlog of Periphery findings in product code, keyed by USR.
///
/// The check fails on a product-code finding whose USRs the baseline does not list. It lists
/// findings in test code without failing on them, and names entries no scan reports any more.
public struct Baseline: Sendable {
  public static let header = """
    # Periphery findings in product code that stay: intentional test seams and contracts,
    # and backlog. The dead-code check fails on any other finding in product code.
    # Each entry is a USR, and its comment names the declaration. Generated by
    # `swift-dead-code baseline --write`; add a finding only for an intentional seam,
    # contract or backlog item you decided to keep, and delete dead code instead.

    """

  /// What a baseline check found.
  public struct Outcome: Sendable, Equatable {
    /// Product-code findings the baseline lacks: these fail the check.
    public var new: [PeripheryFinding]
    /// Findings in test code, listed but never failing.
    public var inTests: [PeripheryFinding]
    /// Baseline entries no scan reports any more.
    public var stale: [String]
  }

  let model: ProjectModel
  let configuration: Configuration

  public init(model: ProjectModel, configuration: Configuration) {
    self.model = model
    self.configuration = configuration
  }

  public var url: URL {
    model.root.appendingPathComponent(configuration.periphery.baseline)
  }

  /// Reads scans; a declaration several scans report counts once, at its first location.
  public static func merge(_ scans: [[PeripheryFinding]]) -> [PeripheryFinding] {
    var byIdentity: [[String]: PeripheryFinding] = [:]
    for scan in scans {
      for finding in scan where byIdentity[finding.identity] == nil {
        byIdentity[finding.identity] = finding
      }
    }
    return byIdentity.values.sorted(by: Self.order)
  }

  /// Splits findings into test code and product code by the project model.
  public func partition(
    _ findings: [PeripheryFinding]
  ) -> (
    product: [PeripheryFinding], tests: [PeripheryFinding]
  ) {
    let testGlobs = configuration.testSupportGlobs
    var product: [PeripheryFinding] = []
    var tests: [PeripheryFinding] = []
    for finding in findings {
      if model.isTestCode(finding.path, testGlobs: testGlobs) {
        tests.append(finding)
      } else {
        product.append(finding)
      }
    }
    return (product, tests)
  }

  /// Compares the scans with the recorded baseline.
  public func check(_ findings: [PeripheryFinding]) throws -> Outcome {
    let (product, tests) = partition(findings)
    let known = try recordedIDs()
    let new = product.filter { finding in
      known.isDisjoint(with: finding.ids)
    }
    let reported = Set(product.flatMap(\.ids))
    return Outcome(new: new, inTests: tests, stale: known.subtracting(reported).sorted())
  }

  /// The baseline text for the product-code findings: one entry per USR, grouped by file.
  public func text(for findings: [PeripheryFinding]) -> String {
    let (product, _) = partition(findings)
    let entries =
      product.flatMap { finding in
        finding.ids.map { usr in
          (finding.path, finding.name, usr, finding.kind)
        }
      }
      .sorted { lhs, rhs in
        (lhs.0, lhs.1, lhs.2, lhs.3) < (rhs.0, rhs.1, rhs.2, rhs.3)
      }
    let lines = entries.map { path, name, usr, kind in
      "\(usr)  # \(path): \(kind) \(name)\n"
    }
    return Self.header + lines.joined()
  }

  /// Rewrites the baseline with the product-code findings.
  public func write(_ findings: [PeripheryFinding]) throws -> Int {
    try TextFiles.write(text(for: findings), to: url)
    return partition(findings).product.count
  }

  /// The USRs the baseline lists; each entry's first word is one.
  public func recordedIDs() throws -> Set<String> {
    guard FileManager.default.fileExists(atPath: url.path) else {
      return []
    }
    guard let text = TextFiles.read(url) else {
      throw DeadCodeError.usage("cannot read \(configuration.periphery.baseline)")
    }
    return Set(
      text.split(separator: "\n")
        .filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty && !$0.hasPrefix("#") }
        .compactMap { $0.split(separator: " ").first.map(String.init) }
    )
  }

  /// Sorted as the scans' `path:line:column` strings compare, then by the other fields.
  static func order(_ lhs: PeripheryFinding, _ rhs: PeripheryFinding) -> Bool {
    if (lhs.location, lhs.kind, lhs.name, lhs.hint) != (rhs.location, rhs.kind, rhs.name, rhs.hint)
    {
      return (lhs.location, lhs.kind, lhs.name, lhs.hint)
        < (rhs.location, rhs.kind, rhs.name, rhs.hint)
    }
    return lhs.ids.lexicographicallyPrecedes(rhs.ids)
  }
}

public extension Configuration {
  /// `test_support` entries that are path globs rather than target names.
  var testSupportGlobs: [Glob] {
    testSupport.filter { $0.contains("/") || $0.contains("*") }.map(Glob.init)
  }
}
